#!/usr/bin/env python3
"""Generate crates/modules/<app>/Cargo.toml from the upstream app's binary manifest.

An adapter compiles the upstream binary's sources (see crates/studio-overlay), so it needs the
binary's dependencies. They are copied from upstream/<app>/apps/<bin>/Cargo.toml with
`workspace = true` entries resolved against upstream/<app>/Cargo.toml and path dependencies
rebased onto the adapter directory. Run it after every upstream sync:

    python3 -I scripts/gen-module-manifests.py            # every module in MODULES
    python3 -I scripts/gen-module-manifests.py wordcraft
"""
import os
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# module id -> (upstream repo, binary crate directory inside it)
MODULES = {
    "photocraft": ("photocraft", "apps/photocraft"),
    "lightcraft": ("lightcraft", "apps/lightcraft"),
    "filmcraft": ("filmcraft", "apps/filmcraft"),
    "pdfcraft": ("pdfcraft", "apps/pdfcraft"),
    "vectorcraft": ("vectorcraft", "apps/vectorcraft"),
    "effectcraft": ("effectcraft", "apps/effectcraft"),
    "wordcraft": ("wordcraft", "apps/wordcraft"),
    "designcraft": ("designcraft", "apps/designcraft"),
    "gridcraft": ("gridcraft", "apps/gridcraft"),
    "cadcraft": ("cadcraft", "apps/cadcraft"),
    "deckcraft": ("deckcraft", "apps/deckcraft"),
    "soundcraft": ("soundcraft", "apps/soundcraft"),
    "artcraft": ("artcraft", "artcraft-native"),
}

# Dependencies the adapter needs whatever the upstream binary uses.
EXTRA = {
    "studio-core": {"path": "../../studio-core"},
}
BUILD = {
    "studio-overlay": {"path": "../../studio-overlay"},
}
# Features removed from every module. Craft Studio renders with wgpu only, and eframe's `glow`
# feature changes `eframe::App::on_exit`'s signature for every app in the build (features are
# unified), which breaks the apps written without it.
DROP_FEATURES = {"eframe": {"glow"}}
# Dependencies taken without their default features. muda (menus) is a macOS-only dependency of
# every app, and its default `gtk3` feature only adds the Linux GTK backend: enabled by one app,
# it puts gtk-rs 0.18 and glib 0.18 (GHSA-wrw7-89jp-8q8g) in Cargo.lock, though never compiled.
NO_DEFAULT_FEATURES = {"muda"}


def rebase(path: str, base: Path, adapter: Path) -> str:
    return os.path.relpath((base / path).resolve(), adapter).replace(os.sep, "/")


def resolve(name: str, spec, workspace_deps: dict, ws_root: Path, bin_dir: Path, adapter: Path):
    if isinstance(spec, str):
        return {"version": spec}
    spec = dict(spec)
    if spec.pop("workspace", False):
        base = workspace_deps.get(name)
        if base is None:
            raise SystemExit(f"{name}: workspace = true but not in [workspace.dependencies]")
        base = {"version": base} if isinstance(base, str) else dict(base)
        if "path" in base:
            base["path"] = rebase(base["path"], ws_root, adapter)
        features = list(dict.fromkeys(base.get("features", []) + spec.pop("features", [])))
        base.update(spec)
        if features:
            base["features"] = features
        return base
    if "path" in spec:
        spec["path"] = rebase(spec["path"], bin_dir, adapter)
    return spec


def value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {value(x)}" for k, x in v.items()) + " }"
    raise TypeError(v)


def table(name: str, deps: dict) -> list[str]:
    lines = [f"[{name}]"]
    lines += [f"{k} = {value(v)}" for k, v in sorted(deps.items())]
    return lines + [""]


def generate(module: str) -> Path:
    repo, bin_rel = MODULES[module]
    ws_root = ROOT / "upstream" / repo
    bin_dir = ws_root / bin_rel
    adapter = ROOT / "crates" / "modules" / module
    ws = tomllib.loads((ws_root / "Cargo.toml").read_text())
    manifest = tomllib.loads((bin_dir / "Cargo.toml").read_text())
    workspace_deps = ws.get("workspace", {}).get("dependencies", {})

    def deps_of(t: dict) -> dict:
        deps = {n: resolve(n, s, workspace_deps, ws_root, bin_dir, adapter) for n, s in t.items()}
        for name, drop in DROP_FEATURES.items():
            if name in deps and "features" in deps[name]:
                deps[name]["features"] = [f for f in deps[name]["features"] if f not in drop]
        for name in NO_DEFAULT_FEATURES & deps.keys():
            deps[name]["default-features"] = False
        return deps

    out = [
        f"# Generated by scripts/gen-module-manifests.py from upstream/{repo}/{bin_rel}/Cargo.toml.",
        "# Do not edit: rerun the script after an upstream sync.",
        "",
        "[package]",
        f'name = "studio-{module}"',
        f'description = "Craft Studio module: {module} (upstream {repo}/{bin_rel})"',
        "version.workspace = true",
        "edition.workspace = true",
        "rust-version.workspace = true",
        "license.workspace = true",
        "publish.workspace = true",
        "",
        "[lib]",
        "doctest = false",
        "test = false",
        "",
    ]
    out += table("dependencies", {**deps_of(manifest.get("dependencies", {})), **EXTRA})
    for target, sections in sorted(manifest.get("target", {}).items()):
        if "dependencies" in sections:
            out += table(f"target.'{target}'.dependencies", deps_of(sections["dependencies"]))
    out += table("build-dependencies", BUILD)
    features = manifest.get("features")
    if features:
        out += ["[features]"] + [f"{k} = {value(v)}" for k, v in features.items()] + [""]
    adapter.mkdir(parents=True, exist_ok=True)
    path = adapter / "Cargo.toml"
    path.write_text("\n".join(out))
    return path


def main() -> None:
    for module in sys.argv[1:] or MODULES:
        print(generate(module).relative_to(ROOT))


if __name__ == "__main__":
    main()
